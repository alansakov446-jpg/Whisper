def normalize_lang(lang: str | None) -> str:
    return "en" if (lang or "").lower().startswith("en") else "ru"


def t(lang: str | None, key: str, **kwargs) -> str:
    code = normalize_lang(lang)
    template = STRINGS[code].get(key) or STRINGS["ru"].get(key) or key
    if not kwargs:
        return template
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError, ValueError):
        return template


def instruction(lang: str | None, bot_username: str) -> str:
    return t(lang, "start_text", bot=bot_username) + "\n\n" + t(lang, "anon_note")


def format_ttl(seconds: int | None, lang: str | None) -> str:
    if seconds is None:
        return t(lang, "ttl_forever")
    mapping = {60: "ttl_1m", 3600: "ttl_1h", 86400: "ttl_24h", 604800: "ttl_7d"}
    if seconds in mapping:
        return t(lang, mapping[seconds])
    return humanize_seconds(seconds, normalize_lang(lang))


def humanize_seconds(seconds: int, lang: str) -> str:
    if seconds % 604800 == 0:
        n = seconds // 604800
        return f"{n}w" if lang == "en" else f"{n} нед"
    if seconds % 86400 == 0:
        n = seconds // 86400
        return f"{n}d" if lang == "en" else f"{n} д"
    if seconds % 3600 == 0:
        n = seconds // 3600
        return f"{n}h" if lang == "en" else f"{n} ч"
    if seconds % 60 == 0:
        n = seconds // 60
        return f"{n}m" if lang == "en" else f"{n} мин"
    return f"{seconds}s" if lang == "en" else f"{seconds} с"


def media_kind(lang: str | None, media_type: str | None) -> str:
    key = {
        "photo": "kind_photo",
        "video": "kind_video",
        "document": "kind_document",
        "animation": "kind_animation",
        "voice": "kind_voice",
        "audio": "kind_audio",
        "video_note": "kind_video_note",
    }.get(media_type or "", "kind_file")
    return t(lang, key)
